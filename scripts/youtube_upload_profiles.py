#!/usr/bin/env python3
"""Reusable BR/EN YouTube upload profiles for every AutoEditorVideo uploader.

Video-specific titles, descriptions and topical tags come from editorial
manifests. API-writeable options are shaped strictly for videos.insert.
YouTube Studio-only settings and video-specific AI disclosure need review.
"""
from __future__ import annotations
import json
from pathlib import Path
import re
from typing import Mapping

ROOT=Path(__file__).resolve().parents[1]
PROFILE_FILE=ROOT/"config"/"youtube-upload-profiles.json"
_ALLOWED_CHANNELS={"br","en"}
_PRIVACY={"private","unlisted","public"}


class UploadProfileError(ValueError):
    pass


def load_profiles(path:Path=PROFILE_FILE)->dict:
    data=json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema")!="autoeditorvideo/youtube-upload-profiles/v1":
        raise UploadProfileError("UPLOAD_PROFILE_SCHEMA_MISMATCH")
    for channel in sorted(_ALLOWED_CHANNELS):
        p=data.get(channel)
        if not isinstance(p,dict):
            raise UploadProfileError("MISSING_CHANNEL_PROFILE_"+channel.upper())
        if p.get("language")!=("pt-BR" if channel=="br" else "en-US"):
            raise UploadProfileError("UPLOAD_PROFILE_LANGUAGE_MISMATCH")
        if p.get("category_id")!="1" or p.get("privacy_default")!="private":
            raise UploadProfileError("UPLOAD_PROFILE_UNAPPROVED_CATEGORY_OR_PRIVACY")
        if p.get("youtube_channel_id")!=("UCXGYTuBYn-0Ziqin5ajKhOw" if channel=="br" else "UCBoNbQjaMYdpJqPLRZAFkvQ"):
            raise UploadProfileError("UPLOAD_PROFILE_CHANNEL_ID_MISMATCH")
        cover=p.get("thumbnail") or {}
        if (cover.get("source")!="autoeditorvideo_original_generated_cover"
                or cover.get("must_match_review_artifact_sha256") is not True
                or cover.get("block_video_upload_if_missing_or_invalid") is not True
                or cover.get("fallback_to_auto_generated_youtube_thumbnail") is not False
                or cover.get("fallback_to_video_frame") is not False
                or cover.get("fallback_to_other_channel_cover") is not False
                or cover.get("regenerate_cover_at_publish_time") is not False):
            raise UploadProfileError("GENERATED_THUMBNAIL_PROFILE_VIOLATION")
    return data


def _text(meta:Mapping,key_candidates:tuple[str,...])->str:
    for key in key_candidates:
        value=meta.get(key)
        if isinstance(value,str) and value.strip():
            return value.strip()
    return ""


def _paragraph_dedup(description:str)->str:
    # Avoid the exact repeated paragraphs visible in some Studio paste drafts.
    paragraphs=re.split(r"\n\s*\n", description.replace("\r\n","\n").strip())
    seen=set()
    chosen=[]
    for paragraph in paragraphs:
        normalized=re.sub(r"\s+"," ",paragraph).strip().casefold()
        if normalized and normalized not in seen:
            chosen.append(paragraph.strip())
            seen.add(normalized)
    return "\n\n".join(chosen)


def _topic_tags(meta:Mapping,profile:dict)->list[str]:
    source=meta.get("tags") or []
    if not isinstance(source,list) or any(not isinstance(tag,str) for tag in source):
        raise UploadProfileError("UPLOAD_TAGS_NOT_A_LIST")
    extras=profile["tags"]["priority"]
    excluded={x.casefold() for x in profile["tags"].get("unrelated_blacklist",[])}
    result=[]
    seen=set()
    total=0
    for original in [*source,*extras]:
        tag=re.sub(r"\s+"," ",original.strip().lstrip("#"))
        if not tag or tag.casefold() in seen or tag.casefold() in excluded:
            continue
        if len(tag)>100:
            continue
        delta=len(tag)+(1 if result else 0)
        if total+delta>min(500,profile["tags"]["max_characters"]):
            continue
        result.append(tag)
        seen.add(tag.casefold())
        total+=delta
    return result


def _description(meta:Mapping,channel:str,profile:dict)->str:
    base=_text(meta,("description","descricao","description_youtube","descricao_youtube"))
    if not base:
        raise UploadProfileError("MISSING_AUTHOR_WRITTEN_DESCRIPTION")
    description=_paragraph_dedup(base)
    configuration=profile["description"]
    lower=description.casefold()
    if not any(s in lower for s in (("inscreva","inscrever","acompanhe") if channel=="br" else ("subscribe","follow for more"))):
        description+="\n\n"+configuration["call_to_action"]
    lower=description.casefold()
    disclosure_present=(any(s in lower for s in ("geradas por ia","gerado por ia","ilustrações geradas","geração de imagens","generated illustrations","ai-generated illustrations","generated by ai")))
    if not disclosure_present:
        description+="\n\n"+configuration["original_content_notice"]
    if meta.get("spoilers") is True:
        warning=configuration["spoiler_notice"]
        if "spoiler" not in description.casefold():
            description+="\n\n"+warning
    suffix=[]
    for hashtag in configuration["extra_hashtags"]:
        if not re.search(r"(?<!\w)"+re.escape(hashtag)+r"(?!\w)",description,re.I):
            suffix.append(hashtag)
    if suffix:
        description+="\n\n"+" ".join(suffix)
    if len(description)>5000:
        raise UploadProfileError("YOUTUBE_DESCRIPTION_EXCEEDS_5000")
    return description


def build_insert_body(channel:str,meta:Mapping,*,privacy:str="private")->dict:
    """Build only supported fields for YouTube videos.insert API.

    This does not modify any pre-existing video and never invents an AI
    declaration, an upload title or a video's sponsorship status.
    """
    if channel not in _ALLOWED_CHANNELS:
        raise UploadProfileError("UNKNOWN_CHANNEL")
    if privacy not in _PRIVACY:
        raise UploadProfileError("UNKNOWN_PRIVACY")
    profile=load_profiles()[channel]
    supplied_channel=meta.get("channel_id")
    if supplied_channel is not None and supplied_channel!=profile["youtube_channel_id"]:
        raise UploadProfileError("VIDEO_CHANNEL_ID_DIFFERENT_FROM_PROFILE")
    if meta.get("feito_para_criancas") is True or meta.get("made_for_kids") is True:
        raise UploadProfileError("KIDS_CONTENT_NOT_ALLOWED_ON_OTAKU_CHANNEL")
    title=_text(meta,("title","titulo"))
    if not 1<=len(title)<=100:
        raise UploadProfileError("UPLOAD_TITLE_INVALID_OR_TOO_LONG")
    snippet={
        "title":title,
        "description":_description(meta,channel,profile),
        "tags":_topic_tags(meta,profile),
        "categoryId":profile["category_id"],
        "defaultLanguage":profile["language"],
    }
    status={
        "privacyStatus":privacy,
        "selfDeclaredMadeForKids":False,
        "license":profile["license"],
        "embeddable":profile["embeddable"],
        "publicStatsViewable":profile["public_stats_viewable"],
    }
    synthetic=meta.get("containsSyntheticMedia",meta.get("contains_synthetic_media"))
    if synthetic is not None:
        if type(synthetic) is not bool:
            raise UploadProfileError("AI_DISCLOSURE_REQUIRES_EXPLICIT_BOOLEAN_REVIEW")
        status["containsSyntheticMedia"]=synthetic
    return {"snippet":snippet,"status":status}


def upload_notify_subscribers(channel:str)->bool:
    if channel not in _ALLOWED_CHANNELS:
        raise UploadProfileError("UNKNOWN_CHANNEL")
    return load_profiles()[channel]["notify_subscribers"]


def studio_review_fields(channel:str)->dict:
    if channel not in _ALLOWED_CHANNELS:
        raise UploadProfileError("UNKNOWN_CHANNEL")
    data=load_profiles()
    return {"channel":channel,
            "target_channel_id":data[channel]["youtube_channel_id"],
            "moderation_desired":data[channel]["commentary_moderation_studio"],
            "studio_only":data["studio_only"]}
